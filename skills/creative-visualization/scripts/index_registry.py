#!/usr/bin/env python3
"""Map the HyperFrames registry onto the animation atlas families.
Usage: python3 index_registry.py > ../references/registry-index.md
Runs `npx hyperframes catalog --json`; numbered variants (carousel-circle-1..5) collapse into one row."""
import json, re, subprocess, sys
from collections import defaultdict

FAMILIES = [  # first match wins
    ("Transitions / seams", r"transition|dissolve|warp|glitch|flash|zoom blur|wipe|crossfade|split|seam"),
    ("Logo and brand reveal", r"logo|brand|outro|intro|sting|lockup|extrud"),
    ("Kinetic type and titles", r"headline|title|text|word|type|letter|caption|quote|kinetic|callout"),
    ("UI and device", r"chat|app|phone|iphone|macbook|ios|macos|notification|dashboard|browser|ui |screen|cursor|exchange|prompt|terminal|code|editor|widget|card"),
    ("Data and charts", r"chart|graph|stat|count|number|race|progress|metric|heatmap|data|ticker"),
    ("Maps and places", r"map|flight|route|globe|city|zoom into|country"),
    ("3D and product", r"3d|orbit|exploded|stack|cuboid|glass|chrome|bevel|device|tunnel|camera"),
    ("Particles, fields, shaders", r"particle|dot|halftone|shader|webgpu|noise|aurora|orb|blob|nebula|lines|rays|gradient|marble|liquid|goo"),
    ("Lower thirds and overlays", r"lower third|lt-|overlay|hud|frame|follow|subscribe|badge|tag"),
    ("Carousels and galleries", r"carousel|gallery|grid|mosaic|wall"),
    ("Hand-made looks", r"hand-drawn|handwrit|hw-|scribble|paper|doodle|sketch|crayon"),
    ("Characters", r"character|avatar|walk|lottie"),
]

items = json.loads(subprocess.run(["npx", "-y", "hyperframes", "catalog", "--json"], capture_output=True, text=True, check=True).stdout)
items = items if isinstance(items, list) else items.get("items", [])
groups, seen = defaultdict(list), {}
for it in items:
    name, desc = it.get("name", ""), (it.get("description") or "").strip()
    base = re.sub(r"-\d+$", "", name)
    if base in seen:
        seen[base]["n"] += 1; continue
    text = f"{name} {desc}".lower()
    fam = next((f for f, rx in FAMILIES if re.search(rx, text)), "Other")
    row = {"name": base, "type": it.get("type", "?"), "desc": desc[:140], "n": 1}
    seen[base] = row; groups[fam].append(row)

print(f"# HyperFrames registry index ({len(items)} items, {len(seen)} distinct)\n")
print("Generated by `scripts/index_registry.py`. Install one with `npx hyperframes add <name>`; restyle it to the brief (colours, type, timing). Search before hand-building any named effect.\n")
for fam, _ in FAMILIES + [("Other", "")]:
    rows = groups.get(fam)
    if not rows: continue
    print(f"## {fam} ({len(rows)})\n\n| Block | Variants | What it does |\n|---|---|---|")
    for r in sorted(rows, key=lambda r: r["name"]):
        print(f"| `{r['name']}` | {r['n']} | {r['desc'].replace('|', '/')} |")
    print()
